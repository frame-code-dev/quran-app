/**
 * Mengambil ayat harian berdasarkan tanggal (deterministik per hari).
 * Setiap pergantian hari (00:00), ayat akan berganti secara otomatis.
 */
export function getDailyVerse(date = new Date()) {
  const d = new Date(date);
  // Hitung day of year (0 - 365)
  const start = new Date(d.getFullYear(), 0, 0);
  const diff = d - start + (start.getTimezoneOffset() - d.getTimezoneOffset()) * 60 * 1000;
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);

  const index = Math.abs(dayOfYear) % CURATED_DAILY_VERSES.length;
  return {
    ...CURATED_DAILY_VERSES[index],
    index,
  };
}

/**
 * Mengambil ayat acak dari koleksi jika pengguna ingin melihat ayat lain.
 */
export function getRandomVerse(excludeIndex) {
  if (CURATED_DAILY_VERSES.length <= 1) return { ...CURATED_DAILY_VERSES[0], index: 0 };
  let nextIdx = Math.floor(Math.random() * CURATED_DAILY_VERSES.length);
  if (nextIdx === excludeIndex) {
    nextIdx = (nextIdx + 1) % CURATED_DAILY_VERSES.length;
  }
  return {
    ...CURATED_DAILY_VERSES[nextIdx],
    index: nextIdx,
  };
}
